const assert = require('node:assert/strict');
const path = require('node:path');
const Module = require('node:module');
const {buildSync} = require('esbuild');
const mod = new Module(__filename); mod.paths = module.paths;
mod._compile(buildSync({entryPoints:[path.resolve(__dirname,'../src/publicationVisibility.ts')],bundle:true,write:false,platform:'node',format:'cjs'}).outputFiles[0].text,__filename);
const {groupPublications, platformPublication, pendingPlatformPublication, publicationReplaced, publicationState} = mod.exports;
const make = (id, extra={}) => ({id,project_id:'p',version_id:'v',title:'标题',body:'正文',topics:[],kind:'image',asset_ids:['a'],ready:true,target_platform:'xhs',...extra});
const root = make('root',{manual_status:'published',remote_work_id:'xhs-remote'});
const dy = make('dy',{target_platform:'douyin',shared_draft_id:'root'});
let groups = groupPublications([dy,root]);
assert.equal(groups.length,1); assert.equal(groups[0].id,'root');
assert.equal(platformPublication(groups[0],'douyin').id,'dy');
assert.equal(publicationState(platformPublication(groups[0],'xhs')),'published');
assert.equal(publicationState(platformPublication(groups[0],'douyin')),'ready');
const virtual = pendingPlatformPublication(groupPublications([root])[0],'douyin');
assert.equal(virtual.remote_work_id,''); assert.equal(virtual.manual_status,'ready');
assert.equal(virtual.online_state,''); assert.deepEqual(virtual.asset_ids,root.asset_ids);
assert.equal(groupPublications([root,make('legacy',{target_platform:'douyin'})]).length,1);
assert.equal(groupPublications([root,make('same-platform')]).length,2);
assert.equal(groupPublications([root,make('other-version',{target_platform:'douyin',version_id:'v2'})]).length,2);
assert.equal(groupPublications([root,make('other-content',{target_platform:'douyin',body:'新正文'})]).length,2);
assert.equal(groupPublications([root,make('other-assets',{target_platform:'douyin',asset_ids:['b']})]).length,2);
assert.equal(groupPublications([make('a',{group_id:'g'}),make('b',{target_platform:'douyin',version_id:'edited',group_id:'g'})]).length,1);
const latest = make('latest',{version_id:'next',workflow_managed:true,updated_at:'2026-11-11'});
assert.equal(publicationReplaced(dy,[root,dy,latest]),false);
assert.equal(publicationReplaced({...root,manual_status:'ready',remote_work_id:''},[{...root,manual_status:'ready',remote_work_id:''},dy,latest]),true);
assert.equal(publicationReplaced(dy,[{...root,manual_status:'ready',remote_work_id:'',deleted_at:'deleted'},dy,latest]),true);
assert.equal(publicationReplaced(make('legacy-dy',{target_platform:'douyin'}),[root,make('legacy-dy',{target_platform:'douyin'}),make('new-dy',{target_platform:'douyin',version_id:'next',workflow_managed:true})]),false);
console.log('PASS: shared draft grouping, independent statuses, virtual platform state, historical replacement visibility.');
