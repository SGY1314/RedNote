const assert = require('node:assert/strict');
const path = require('node:path');
const Module = require('node:module');
const { buildSync } = require('esbuild');
const source = buildSync({entryPoints:[path.join(__dirname,'../src/rewriteFormats.ts')],bundle:true,write:false,platform:'node',format:'cjs'}).outputFiles[0].text;
const mod = new Module('rewriteFormats');mod._compile(source,'rewriteFormats.cjs');
const { projectHasKind, versionsForKind, draftKey, readFormatDraft, clearFormatDraft } = mod.exports;
const values = new Map();
global.localStorage = { getItem:k=>values.get(k)||null,setItem:(k,v)=>values.set(k,v),removeItem:k=>values.delete(k) };
assert.equal(projectHasKind({kind:'image'},'video'),false);
assert.equal(projectHasKind({kind:'video'},'image'),false);
assert.equal(projectHasKind({kind:'video',media_selections:{image:{asset_ids:['old-photo']}}},'image'),true);
const versions=[{id:'i',media:{kind:'image'}},{id:'v',media:{kind:'video'}},{id:'old'}];
assert.deepEqual(versionsForKind(versions,'image','video').map(v=>v.id),['i']);
assert.deepEqual(versionsForKind(versions,'video','video').map(v=>v.id),['v','old']);
localStorage.setItem('gin.draft.p',JSON.stringify({content:{body:'旧视频草稿'},media:{kind:'video',asset_ids:['video']}}));
assert.equal(readFormatDraft('p','image','image'),null,'video draft must not enter image editor');
assert.equal(readFormatDraft('p','video','image').content.body,'旧视频草稿');
localStorage.setItem(draftKey('p','image'),JSON.stringify({content:{body:'新图文草稿'},media:{kind:'image',asset_ids:['photo']}}));
assert.equal(readFormatDraft('p','image','video').content.body,'新图文草稿');
clearFormatDraft('p','image','video');
assert.equal(readFormatDraft('p','image','image'),null);
assert.equal(readFormatDraft('p','video','image').content.body,'旧视频草稿','saving images must preserve video draft');
localStorage.setItem(draftKey('p','image'),JSON.stringify({content:{body:'保留图片'}}));
clearFormatDraft('p','video','image');
assert.equal(readFormatDraft('p','video','image'),null);
assert.equal(readFormatDraft('p','image','video').content.body,'保留图片');
console.log('PASS: format list/version separation and independent draft migration/clearing');
