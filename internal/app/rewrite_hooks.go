package app

import "fmt"

const rewriteWritingRules = `写作规则（默认以发帖作者的自然表达为目标）：
1. 软件使用者是最终发帖作者，读者是帖子受众。直接写可发布的标题、正文和话题，不对使用者讲解写法，不出现“以下是为你生成的文案”等助手口吻。
2. 标题、开头和正文承诺一致，正文回答开头提出的问题，不制造假悬念。吸引力来自具体内容，不靠夸张标题或强行套用钩子；缺少真实故事、反差或收益依据时自然直述。
3. 根据目标读者、语气、篇幅和补充要求组织内容。像作者向一个关心此事的人讲清楚自己的内容：用熟悉的词、自然的衔接，句子长短随意思变化；分段按语意，不把每句都拆成一行。
4. 优先保留用户明确提供的个人观点、偏好和用词习惯，在不改变原意的前提下让表达顺畅。用户选择专业、正式或其他语气时尊重该选择，不强行改成聊天腔。
5. 只使用参考资料和用户明确提供的事实。不编造第一人称经历、数据、权威背书、产品效果或收益承诺；参考博主的经历不能改写成使用者的经历。只有用户明确说明是自己的经历时，才写“我亲测”“我用了一个月”等。没有个人资料时也能平实、有温度地说明，不硬凑第一人称。
6. 多写资料支持的具体动作、观察、细节、解释或可执行方法，少用抽象评价代替内容。不为了显得真实而杜撰时间、地点、对话、情绪、挫折或生活细节；必要的假设示例要标明是示例。
7. 保留事实含义，用独立结构表达，不逐句替换同义词。不机械套用“痛点—干货—升华”结构，不每篇都分成三点，不滥用“首先、其次、最后、总之”；教程确实需要步骤时可以列清单。
8. 不默认使用“家人们”“宝子们”“谁懂啊”“狠狠爱了”“绝绝子”“一定要看”等流行套话，不堆叠表情、感叹号和标签。仅在用户明确要求相应风格时适量使用；不靠故意错别字、语病或杂乱排版模拟真人。
9. 结尾在内容讲完时自然停下，或给一个具体建议；有实际讨论点才提问，不强行升华、灌鸡汤，也不机械要求点赞、收藏、关注。
10. 输出前自行删掉重复意思、空话和模板句，检查读起来是否顺口、是否符合作者要求、是否冒用了他人经历。只返回规定的成稿 JSON，不输出自检、分析或“人味优化说明”。示例措辞只用于说明规则，不要作为内容反复照搬。`

func rewriteHookInstruction(hook string) (string, string, error) {
	if hook == "" {
		hook = "auto"
	}
	rules := map[string]string{
		"auto":     "自动选择：根据参考资料和目标读者选择一种合适的开头，默认自然表达，无需在成稿中解释所选策略。",
		"pain":     "痛点共鸣：以读者在此主题下可能遇到的具体问题切入，避免制造焦虑或断言所有人都有该问题。",
		"benefit":  "明确收益：说明读者能从本文获得的知识或方法，收益必须由正文支持，不夸大效果。",
		"question": "提问悬念：提出一个与主题相关的具体问题，并在正文中清楚回答，不使用虚假秘密或故意隐瞒答案。",
		"contrast": "反差切入：使用资料中有依据的认知差异或前后对比，引出解释，不编造对比数据。",
		"story":    "故事切入：仅依据用户提供的真实经历或资料场景展开；缺少依据时自然直述，不虚构作者亲身经历。",
		"plain":    "自然直述：直接介绍主题和核心信息，清楚平实，不刻意制造悬念或强加故事。",
	}
	rule, ok := rules[hook]
	if !ok {
		return "", "", fmt.Errorf("请选择有效的文案钩子")
	}
	return hook, "文案钩子：" + rule + "\n" + rewriteWritingRules, nil
}
